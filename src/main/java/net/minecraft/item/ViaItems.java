    /** Called once from the static initialiser of {@link Items}, after every vanilla item. */
    static void register() {
        if (done) {
            return;
        }
        done = true;
        for (int i = 0; i < ID.length; ++i) {
            ResourceLocation key = new ResourceLocation(ID[i]);
            if (Registry.ITEM.containsKey(key)) {
                continue;
            }
            Item item = Registry.register(Registry.ITEM, key, new Item(new Item.Properties()));
            BY_NAME.putIfAbsent(EN[i].toLowerCase(Locale.ROOT), item);
            StringBuilder sb = new StringBuilder();
            for (String w : ID[i].split("_")) {
                if (!w.isEmpty()) {
                    sb.append(sb.length() == 0 ? "" : " ").append(Character.toUpperCase(w.charAt(0))).append(w.substring(1));
                }
            }
            BY_NAME.putIfAbsent(sb.toString().toLowerCase(Locale.ROOT), item);
        }
    }
